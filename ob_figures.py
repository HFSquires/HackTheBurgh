def paydays(tx, persons):
    """Salary credit dates per person: `BGC` credits to the main account (12 each)."""
    sal = tx[(tx.code == "BGC") & (tx.cd == "Credit") & (tx.status == "Booked")]
    out = {p: sorted(sal[sal.persona == p].date) for p in persons}
    assert all(len(v) == 12 for v in out.values()), {p: len(v) for p, v in out.items() if len(v) != 12}
    return out


def payday_table(s, tx, persons):
    ev = s[~s.oneoff].groupby(["persona", "date"]).amount.sum()
    pd_ = paydays(tx, persons)
    days = list(range(-5, 11))
    rows = {}
    for p in persons:
        dl = ev.loc[p] if p in ev.index.get_level_values(0) else pd.Series(dtype=float)
        acc = {k: [] for k in days}
        for P in pd_[p]:
            if P + dt.timedelta(days=-5) >= START and P + dt.timedelta(days=10) <= END:  # full window only
                for k in days:
                    acc[k].append(dl.get(P + dt.timedelta(days=k), 0.0))
        rows[p] = {k: float(np.mean(v)) if v else np.nan for k, v in acc.items()}
    per = pd.DataFrame(rows).T  # persons x day
    return per, {p: sum(1 for P in v if P - dt.timedelta(days=5) >= START and P + dt.timedelta(days=10) <= END)
                 for p, v in pd_.items()}


