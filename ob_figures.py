        d = json.load(open(f, encoding="utf-8"))
        pid = d["Meta"]["Persona"]
        ts = [t for p in d["Providers"] for t in p["Data"]["Transaction"]]
        refs = [t["TransactionReference"] for t in ts]
        e = o = 0.0
        biggest = {}
